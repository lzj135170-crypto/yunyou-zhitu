# 行程类意图。宁可略宽：宽了最多多补几个 POI 块，窄了会漏掉
# 「三天怎么玩」「4天3晚」这类常见问法。
_ITINERARY_RE = re.compile(
    r"("
    r"几[天日]|多少天|"
    r"[一二三四五六七八九十两\d]+[天日](?:[一二三四五六七八九十两\d]+晚)?|"
    r"一日游|二日游|三日游|四日游|五日游|"
    r"行程|安排|路线|怎么玩|游玩顺序|规划|day\s*\d+|"
    r"[一二三四五六七八九十两\d]+天[一二三四五六七八九十两\d]+晚"
    r")",
    re.IGNORECASE,
)


def is_itinerary_query(query: str) -> bool:
    """这句是不是行程类问题。纯规则，不调模型。"""
    return bool(_ITINERARY_RE.search(query or ""))


def extract_pois(text: str) -> list[str]:
    """按首次出现顺序返回文本中的 POI canonical；用子串匹配，不依赖分词。"""
    if not text:
        return []

    first_at: dict[str, int] = {}
    for canonical, aliases in POI_ALIASES:
        for alias in aliases:
            idx = text.find(alias)
            if idx < 0:
                continue
            if canonical not in first_at or idx < first_at[canonical]:
                first_at[canonical] = idx

    return [name for name, _ in sorted(first_at.items(), key=lambda kv: (kv[1], kv[0]))]
